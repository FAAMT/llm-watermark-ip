#!/usr/bin/env python3
"""CPU baselines for the IP's two jobs, each checked against the golden model:
a scalar C loop built with gcc -O3, and the NumPy golden model itself.

    python3 scripts/baseline.py     -> results/baseline.md, results/baseline.json
"""
import json
import pathlib
import platform
import subprocess
import sys
import time

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from wmtb import ROOT, BUILD, W  # noqa: E402

PERF = json.loads((ROOT / "results" / "perf.json").read_text())


def cpu_name():
    try:
        for line in open("/proc/cpuinfo"):
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor()


def main():
    BUILD.mkdir(exist_ok=True)
    exe = BUILD / "wm_baseline"
    subprocess.run(["gcc", "-O3", "-march=native", "-o", str(exe), "src/sw/wm_baseline.c"], check=True, cwd=ROOT)
    rows = []
    for V in (50257, 151936):
        out = subprocess.run([str(exe), "src/rtl/rom/gumbel_rom.hex", "src/rtl/rom/score_rom.hex", str(V), "200", "1"],
                             check=True, cwd=ROOT, capture_output=True, text=True).stdout.split("\n")
        s = out[0].split(); d = out[1].split()
        c_ns = float(s[3])
        rng = np.random.default_rng(0)
        lg = W.to_q88(rng.normal(0, 3, V))
        t0 = time.perf_counter()
        for r in range(5):
            W.sample(0x0123456789ABCDEF, [r], lg)
        np_ns = (time.perf_counter() - t0) / 5 * 1e9
        hw = next(r for r in PERF["sample"] if r["V"] == V)
        rows.append(dict(V=V, c_us=c_ns / 1e3, numpy_us=np_ns / 1e3, ip_us=hw["us"], ip_cycles=hw["latency"],
                         detect_c_ns_per_token=float(d[4])))
    # bit-exactness of the C loop against the golden model, on golden-generated inputs
    rng = np.random.default_rng(11)
    checks = 0
    for V in (1, 5, 1000, 50257):
        lg = W.to_q88(rng.normal(0, 3, V)); toks = [int(x) for x in rng.integers(V, size=500)]
        (BUILD / "chk_l.txt").write_text("\n".join(str(int(x)) for x in lg))
        (BUILD / "chk_t.txt").write_text("\n".join(map(str, toks)))
        got = subprocess.run([str(exe), "src/rtl/rom/gumbel_rom.hex", "src/rtl/rom/score_rom.hex", "check",
                              str(BUILD / "chk_l.txt"), str(BUILD / "chk_t.txt")],
                             check=True, cwd=ROOT, capture_output=True, text=True).stdout.split()
        t, v = W.sample(0x0123456789ABCDEF, [7], lg)
        S, g, N = W.detect(0x0123456789ABCDEF, toks, [False] * len(toks), 2, 0.25)
        assert [int(x) for x in got] == [t, v, S, g, N], (V, got, (t, v, S, g, N))
        checks += 1
    (ROOT / "results" / "baseline.json").write_text(json.dumps(dict(cpu=cpu_name(), rows=rows), indent=1))
    det = PERF["detect"][-1]
    out = ["# Software baselines", "",
           "Generated by `python3 scripts/baseline.py`. The C loop `src/sw/wm_baseline.c` is the scalar form of",
           "the IP's datapath (two hashes, ROM address, ROM read, add, compare per token), built with",
           f"`gcc -O3 -march=native` and run on one core of this machine ({cpu_name()}).",
           "The IP column is the measured RTL latency at the 100 MHz target clock (results/perf.md).",
           f"The C loop matches the golden model bit for bit on {checks} SAMPLE and DETECT checks.", "",
           "| job | V | C, one core | NumPy golden model | IP at 100 MHz | IP cycles |", "|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| SAMPLE, GUMBEL | {r['V']:,} | {r['c_us']:.0f} µs | {r['numpy_us']:.0f} µs | {r['ip_us']:.1f} µs | {r['ip_cycles']:,} |")
    out.append(f"| DETECT, per token | — | {rows[0]['detect_c_ns_per_token']:.1f} ns | — | "
               f"{1e3 / (det['tokens_per_cycle'] * 100):.1f} ns | {1 / det['tokens_per_cycle']:.2f} |")
    out += ["", "The desktop core runs at several GHz and is shown as an upper bound on CPU software. The",
            "PYNQ-Z2's Cortex-A9 at 650 MHz has not been measured; it would be several times slower than",
            "the desktop figure."]
    (ROOT / "results" / "baseline.md").write_text("\n".join(out) + "\n")
    print("\n".join(out[6:]))


if __name__ == "__main__":
    main()
