#!/usr/bin/env python3
"""Latency and throughput of the RTL, measured in the cycle-accurate simulation
at the IP's ports (no bubbles, no backpressure), for SAMPLE across vocabulary
sizes and DETECT across text lengths. Every response is also checked against
the golden model.

    python3 scripts/perf.py      -> results/perf.md, results/perf.json
"""
import json
import pathlib
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import wmtb as T  # noqa: E402

F_MHZ = 100.0
KEY, NONCE = 0x0123456789ABCDEF, 0x5EED


def main():
    rng = np.random.default_rng(3)
    rows_s, rows_d, ok_all = [], [], True
    for V in (4, 64, 1024, 4096, 50257, 151936):
        a = T.Activation().config(1, V, KEY, NONCE, k=1)
        a.sample(2, T.rand_logits(rng, V), [1], step=0)
        ok, r = T.run([a.end(3)], f"perf_s{V}")
        ok_all &= ok
        r = r[0]
        H = dict((int(d) & 0xFF, c) for c, d in r["H"])            # cmd -> cycle of its header word
        nb = (V + 3) // 4
        lat = r["Z"][0] - H[1]
        rows_s.append(dict(V=V, beats=nb, latency=lat, overhead=lat - nb, us=lat / F_MHZ,
                           data_phase=r["L"][0] - H[1], ok=ok))
    for Tn in (2, 64, 1024, 16384):
        a = T.Activation().config(1, 50257, KEY, NONCE, k=2)
        a.detect(2, [int(x) for x in rng.integers(50257, size=Tn)])
        ok, r = T.run([a.end(3)], f"perf_d{Tn}")
        ok_all &= ok
        r = r[0]
        H = dict((int(d) & 0xFF, c) for c, d in r["H"])
        nb = (Tn + 1) // 2
        lat = r["Z"][0] - H[2]
        rows_d.append(dict(T=Tn, beats=nb, latency=lat, overhead=lat - nb, us=lat / F_MHZ,
                           tokens_per_cycle=Tn / lat, ok=ok))
    (T.ROOT / "results" / "perf.json").write_text(json.dumps(dict(sample=rows_s, detect=rows_d), indent=1))
    out = ["# Latency and throughput (RTL simulation)", "",
           "Generated by `python3 scripts/perf.py`. Cycles are counted by the testbench at the IP's ports,",
           "from the cycle the command's first header word is accepted to the cycle its response's TLAST",
           "word is accepted, with no input bubbles and no output backpressure. Microseconds assume the",
           f"{F_MHZ:.0f} MHz target clock, which synthesis has not yet confirmed. Every response matched the golden model.",
           "", "## SAMPLE", "",
           "| V | data beats ⌈V/4⌉ | latency (cycles) | latency − beats | at 100 MHz |", "|---|---|---|---|---|"]
    for r in rows_s:
        out.append(f"| {r['V']:,} | {r['beats']:,} | {r['latency']:,} | {r['overhead']} | {r['us']:.2f} µs |")
    out += ["", "## DETECT", "",
            "| T tokens | data beats ⌈T/2⌉ | latency (cycles) | latency − beats | tokens per cycle |", "|---|---|---|---|---|"]
    for r in rows_d:
        out.append(f"| {r['T']:,} | {r['beats']:,} | {r['latency']:,} | {r['overhead']} | {r['tokens_per_cycle']:.3f} |")
    oh_s = {r["overhead"] for r in rows_s}
    oh_d = {r["overhead"] for r in rows_d}
    out += ["", f"Latency minus beats is constant ({', '.join(map(str, sorted(oh_s)))} cycles for SAMPLE,",
            f"{', '.join(map(str, sorted(oh_d)))} for DETECT) at every size, so both paths accept one beat per",
            "cycle: an initiation interval of 1."]
    (T.ROOT / "results" / "perf.md").write_text("\n".join(out) + "\n")
    print("\n".join(out[8:]))
    sys.exit(0 if ok_all else 1)


if __name__ == "__main__":
    main()
