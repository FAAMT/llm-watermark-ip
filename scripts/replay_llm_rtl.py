#!/usr/bin/env python3
"""Replay recorded real-model generation steps through the RTL.

For two texts from scripts/llm_eval.py (one per scheme) the first STEPS steps
are sent to the cycle-accurate simulation exactly as the host would send them:
CONFIG with that text's nonce, then one SAMPLE per step with the full
V = 151,936 int16 logit vector and the context, then DETECT on the whole text.
The RTL must pick the token the text actually contains at every step, and
return the same S, g and N as the golden model.

    python3 scripts/replay_llm_rtl.py     -> results/llm_rtl_replay.md
"""
import json
import pathlib
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import wmtb as T  # noqa: E402
from wmtb import W  # noqa: E402

V, KEY, STEPS = 151936, 0x0123456789ABCDEF, 40


def main():
    texts = [json.loads(l) for l in open(T.ROOT / "build" / "llm" / "texts.jsonl")]
    picks = [next(t for t in texts if t["scheme"] == "gumbel" and t["k"] == 2 and t["temp"] == 0.7),
             next(t for t in texts if t["scheme"] == "green" and t["k"] == 1 and t["temp"] == 1.0)]
    lines = ["# Real-model steps replayed through the RTL", "",
             "Generated by `python3 scripts/replay_llm_rtl.py`. Each SAMPLE carries the full V = 151,936",
             "logit vector (37,984 beats) recorded from Qwen3-Coder-30B-A3B by `scripts/llm_eval.py`.", "",
             "| text | scheme | k | temperature | SAMPLE steps | RTL token = text token | DETECT (S, g, N) = golden | cycles per SAMPLE |",
             "|---|---|---|---|---|---|---|---|"]
    ok_all = True
    for t in picks:
        scheme = W.GUMBEL if t["scheme"] == "gumbel" else W.GREEN
        a = T.Activation().config(1, V, KEY, t["nonce"], gamma=0.25, delta=2.0, k=t["k"], scheme=scheme)
        n = min(STEPS, len(t["steps"]))
        for s in range(n):
            st = t["steps"][s]
            lg = np.full(V, -32768, np.int16); lg[st["ids"]] = st["q"]
            a.sample(10 + s, lg, st["ctx"], step=s, free=st["free"])
            assert a.last_sample[0] == st["tok"], "golden model disagrees with the recorded text"
        toks = t["tokens"]
        a.detect(500, toks, skip=W.repeat_flags(toks, t["k"]))
        ok, rows = T.run([a.end(501)], f"replay_{t['scheme']}")
        ok_all &= ok
        r = rows[0]
        got_tokens = [w & 0xFFFFFF for w in r["got"][1:2 * n:2]]
        match = sum(g == st["tok"] for g, st in zip(got_tokens, t["steps"][:n]))
        det_ok = r["got"][2 * n:] == r["want"][2 * n:]
        Hs = [c for c, d in r["H"] if (int(d) & 0xFF) == 1]
        cyc = int(np.median([z - h for h, z in zip(Hs, r["Z"])]))
        lines.append(f"| prompt {t['prompt']} | {t['scheme'].upper()} | {t['k']} | {t['temp']} | {n} | {match} of {n} | "
                     f"{'yes' if det_ok else 'NO'} | {cyc:,} |")
    lines += ["", "Every response word, including the winning values, also matched the golden model."
              if ok_all else "MISMATCH: see build/ for the raw output."]
    (T.ROOT / "results" / "llm_rtl_replay.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[-5:]))
    sys.exit(0 if ok_all else 1)


if __name__ == "__main__":
    main()
