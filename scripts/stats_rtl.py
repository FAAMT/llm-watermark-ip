#!/usr/bin/env python3
"""Distribution check through the RTL: the sampler must draw from softmax(l) in
GUMBEL mode (over random keys/contexts) and from softmax(l + delta*green) in
GREEN mode. 20,000 SAMPLE commands per scheme run through the cycle-accurate
simulation; every response is also compared with the golden model.

    python3 scripts/stats_rtl.py     -> results/stats_rtl.md
"""
import pathlib
import sys

import numpy as np
from scipy.stats import chi2

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import wmtb as T  # noqa: E402
from wmtb import W  # noqa: E402

N = 20000
KEY, NONCE = 0x0123456789ABCDEF, 0x5EED


def counts(rows, V):
    c = np.zeros(V)
    for r in rows:
        for w in r["got"][1::2]:                   # payload words
            c[w & 0xFFFFFF] += 1
    return c


def main():
    lg = np.array([0.0, -0.5, -1.0, -2.0, -3.0]); q = W.to_q88(lg); V = len(q)
    lines = ["# Sampling distribution through the RTL", "",
             f"Generated by `python3 scripts/stats_rtl.py`. {N:,} SAMPLE commands per scheme through the",
             "cycle-accurate simulation, every response also matched against the golden model. The",
             "target distribution is computed from the int16 Q8.8 logits the IP actually receives.", "",
             "| scheme | how the randomness varies | target | χ² (4 degrees of freedom) | p-value | responses equal to the golden model |",
             "|---|---|---|---|---|---|"]
    ok_all = True
    # GUMBEL: the context changes every command, so the keyed noise is fresh each time
    a = T.Activation().config(1, V, KEY, NONCE, k=1)
    for s in range(N):
        a.sample(s & 0xFFFF, q, [s], step=s)
    ok, rows = T.run([a.end(1)], "stats_gumbel")
    ok_all &= ok
    c = counts(rows, V)
    p = np.exp(q / 256.0); p /= p.sum()
    x2 = float(((c - N * p) ** 2 / (N * p)).sum())
    lines.append(f"| GUMBEL | context = step index, 0 … {N - 1} | softmax(l) | {x2:.2f} | {chi2.sf(x2, V - 1):.2f} | {'all' if ok else 'NO'} |")
    # GREEN: fixed context (fixed green set), the unkeyed noise changes with the step
    ctx = [7]
    gr = W.mask(KEY, ctx, V, 0.4)
    a = T.Activation().config(1, V, KEY, NONCE, k=1, scheme=W.GREEN, gamma=0.4, delta=2.0)
    for s in range(N):
        a.sample(s & 0xFFFF, q, ctx, step=s)
    ok, rows = T.run([a.end(1)], "stats_green")
    ok_all &= ok
    c = counts(rows, V)
    p = np.exp(q / 256.0 + 2.0 * gr); p /= p.sum()
    x2 = float(((c - N * p) ** 2 / (N * p)).sum())
    lines.append(f"| GREEN, γ 0.4, δ 2.0 | fixed context, step 0 … {N - 1} | softmax(l + δ·green), green set {gr.astype(int).tolist()} | {x2:.2f} | {chi2.sf(x2, V - 1):.2f} | {'all' if ok else 'NO'} |")
    lines += ["", "A p-value above 0.05 means the observed frequencies are consistent with the target."]
    (T.ROOT / "results" / "stats_rtl.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[-4:]))
    sys.exit(0 if ok_all else 1)


if __name__ == "__main__":
    main()
