#!/usr/bin/env python3
"""Unit tests for the arithmetic blocks, against the golden model, bit for bit:
fmix32_pipe, fmix64_pipe, pf_index (rom_index) and ctx_fold (seed_unit's fold).
Random vectors plus the edge cases listed in plans/design.md.

    python3 scripts/test_units.py     -> results/unit_tests.md
"""
import pathlib
import subprocess
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from wmtb import ROOT, BUILD, W, M32, M64  # noqa: E402

LAT = {"fmix32": 5, "fmix64": 5, "pf_index": 1, "ctx_fold": 2}   # MUL_REG = 1


def fold(key, c, k):
    x = key
    for j in range(k):
        x ^= ((c[j] + 1) * W.C_CTX[j]) & M64
    return x


def main():
    rng = np.random.default_rng(7)
    edges32 = [0, 1, 2, 3, 0x7FFFFFFE, 0x7FFFFFFF, 0x80000000, 0x80000001, 0xFFFFFFFE, 0xFFFFFFFF,
               0x00FFFFFF, 0x01000000, 0x00800000, 0x007FFFFF, 0xFF800000, 0xFF7FFFFF]
    edges32 += [(1 << s) for s in range(32)] + [M32 - (1 << s) for s in range(32)]
    n = 20000
    u32 = edges32 + [int(x) for x in rng.integers(0, 1 << 32, size=n, dtype=np.uint64)]
    u64 = [0, 1, M64, 1 << 63, (1 << 63) - 1] + [int(x) | (int(y) << 32) for x, y in
                                                 zip(rng.integers(0, 1 << 32, size=len(u32), dtype=np.uint64),
                                                     rng.integers(0, 1 << 32, size=len(u32), dtype=np.uint64))]
    u64 = u64[:len(u32)]
    keys = [int(x) | (int(y) << 32) for x, y in zip(rng.integers(0, 1 << 32, size=len(u32), dtype=np.uint64),
                                                     rng.integers(0, 1 << 32, size=len(u32), dtype=np.uint64))]
    cs = rng.integers(0, 1 << 24, size=(len(u32), 4))
    cs[:8] = (1 << 24) - 1
    ks = rng.integers(1, 5, size=len(u32))
    BUILD.mkdir(exist_ok=True)
    fin, fout = BUILD / "units.in.txt", BUILD / "units.out.txt"
    with open(fin, "w") as f:
        for i in range(len(u32)):
            c = cs[i]
            f.write(f"{u32[i]:08x} {u64[i]:016x} {keys[i]:016x} {c[0]} {c[1]} {c[2]} {c[3]} {ks[i]}\n")
    vvp = BUILD / "tb_units.vvp"
    subprocess.run(["iverilog", "-g2012", "-o", str(vvp), "-s", "tb_units", "src/tb/tb_units.v", "src/rtl/wm_util.v"],
                   check=True, cwd=ROOT)
    subprocess.run(["vvp", "-n", str(vvp), f"+in={fin}", f"+out={fout}"], check=True, cwd=ROOT, capture_output=True)
    out = [l.split() for l in open(fout)]
    # line j is printed one cycle after input j is applied: block output for input i appears at line i + LAT - 1
    want32 = W.fmix32(np.array(u32, dtype=np.uint64))
    wantpf = W.pf_index(np.array(u32, dtype=np.uint64))
    res = {}
    res["fmix32"] = sum(int(out[i + LAT["fmix32"] - 1][0], 16) == int(want32[i]) for i in range(len(u32)))
    res["fmix64"] = sum(int(out[i + LAT["fmix64"] - 1][1], 16) == W.fmix64(u64[i]) for i in range(len(u32)))
    res["pf_index"] = sum(int(out[i + LAT["pf_index"] - 1][2], 16) == int(wantpf[i]) for i in range(len(u32)))
    res["ctx_fold"] = sum(int(out[i + LAT["ctx_fold"] - 1][3], 16) == fold(keys[i], [int(c) for c in cs[i]], int(ks[i]))
                          for i in range(len(u32)))
    # the fold followed by fmix64 is the golden step_seed: check that identity in Python
    for i in range(200):
        ctx = [int(c) for c in cs[i][:ks[i]]][::-1]               # oldest first
        assert W.fmix64(fold(keys[i], [int(c) for c in cs[i]], int(ks[i]))) == W.step_seed(keys[i], ctx)
    ok = all(v == len(u32) for v in res.values())
    lines = ["# Unit tests: arithmetic blocks", "",
             "Generated by `python3 scripts/test_units.py` (testbench `src/tb/tb_units.v`). One vector per",
             f"cycle, {len(u32)} vectors per block: {len(edges32)} edge values (0, 1, 2^31 ± 1, 2^32 − 1, every power",
             "of two and its complement, the ROM bank boundaries) and the rest random. Each output is",
             "compared bit for bit with the golden model at the block's latency.", "",
             "| block | golden function | latency (cycles) | vectors matching | result |", "|---|---|---|---|---|"]
    gold = {"fmix32": "`fmix32`", "fmix64": "`fmix64`", "pf_index": "`pf_index`", "ctx_fold": "`step_seed` before its `fmix64`"}
    for b, v in res.items():
        lines.append(f"| `{b}` | {gold[b]} | {LAT[b]} | {v} of {len(u32)} | {'PASS' if v == len(u32) else 'FAIL'} |")
    (ROOT / "results" / "unit_tests.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[-5:]))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
